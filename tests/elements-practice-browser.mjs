import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { ELEMENTS } from '../src/constants/elements.js';
import { createElementPracticeRoom, memoryAnswers, memoryStart } from '../src/utils/memoryGame.js';
const room = createElementPracticeRoom(100000);
assert.equal(room.expiresAt - memoryStart(room), 120000);
assert.equal(room.subway.practice, 'memory');
assert.equal(room.focusGuardEnabled, false);
const names = ELEMENTS.slice(0, 40).map(item => item.name);
assert.deepEqual(memoryAnswers(room), names);
assert.equal(names.at(-1), '지르코늄');
const require = createRequire(import.meta.url);
const { chromium } = require(require.resolve('playwright', { paths: ['C:/Users/User/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules'] }));
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().includes('/api/student-security') || request.url().includes('firestore.googleapis.com')) requests.push(request.url()); });
  await page.clock.install();
  await page.goto('http://127.0.0.1:5180/tests/subway-preview.html?practice=1');
  await page.getByRole('heading', { name: '원소 암기', exact: true }).waitFor();
  await page.screenshot({ path: 'tests/subway-elements-practice-selection-1280.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'tests/subway-elements-practice-selection-390.png', fullPage: true });
  await page.evaluate(() => sessionStorage.setItem('element-hints:undefined', JSON.stringify({ 0: 2 })));
  await page.getByRole('button', { name: /원소 암기/ }).click();
  await page.getByRole('dialog').waitFor();
  assert.equal(await page.locator('.element-study .element-tile').count(), 40);
  await page.getByText('지르코늄', { exact: true }).waitFor();
  await page.clock.fastForward(16000);
  const input = page.getByRole('textbox', { name: '원소 이름 입력' });
  await input.waitFor();
  await page.getByRole('button', { name: '원소기호 힌트 보기 (+3초)' }).click();
  assert.equal(await page.locator('.element-answer').innerText(), 'H\n원소기호 힌트');
  await page.getByRole('button', { name: '정답 이름 보기 (+5초 추가)' }).click();
  assert.deepEqual(await input.evaluate(el => ['paste', 'drop'].map(type => !el.dispatchEvent(new Event(type, { bubbles: true, cancelable: true })))), [true, true]);
  for (const name of names) { await input.fill(name); await input.press('Enter'); }
  await page.getByText('자유연습 기록은 저장되지 않습니다.', { exact: true }).waitFor();
  assert.equal(await page.locator('.element-found').count(), 40);
  assert.equal(await page.evaluate(() => window.practiceApiCalls), 0);
  await page.getByRole('button', { name: '다시 연습하기' }).click();
  await page.getByRole('dialog').waitFor();
  await page.clock.fastForward(16000);
  assert.equal(await page.getByRole('button', { name: '원소기호 힌트 보기 (+3초)' }).isEnabled(), true);
  await page.getByText('+0초', { exact: true }).waitFor();
  await input.fill('수소'); await input.press('Enter');
  await page.evaluate(() => window.requestPracticeSync());
  await page.clock.fastForward(121000);
  await page.getByText('자유연습 기록은 저장되지 않습니다.', { exact: true }).waitFor();
  assert.equal(await page.locator('.element-found').count(), 1);
  assert.equal(await page.locator('.element-missed').count(), 39);
  assert.equal(await input.count(), 0);
  await page.getByRole('button', { name: '다시 연습하기' }).click();
  await page.getByRole('button', { name: '연습 나가기' }).click();
  await page.getByRole('heading', { name: '일반 타자연습' }).waitFor();
  assert.equal(await page.evaluate(() => window.practiceApiCalls), 0);
  assert.deepEqual(requests, []);
  assert.deepEqual(errors, []);
  console.log('Local element practice: forty ordered elements, 15-second study/120-second game, hints, completion, timeout, restart, exit and zero API/Firestore requests passed.');
} finally { await browser.close(); }
